/// <reference lib="dom" />
/* eslint-disable no-console -- command line tool */
/**
 * Template CLI.
 *
 *   pnpm template:new <id> --from minimal      copy a template into templates/<id>/
 *   pnpm template:preview <id> [--print]       live preview on the example data (hot reload)
 *   pnpm template:check <id> [--update-preview] manifest, render, axe-core, PDF print
 *   pnpm --filter @mynto/templates bundle       rebuild src/builtin.generated.ts + docs/templates/*.json
 *
 * <id> is a built-in template (packages/templates/builtin/<id>) or a folder
 * in templates/<id> at the repo root, or a path to a template folder.
 */
import { existsSync } from 'node:fs';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import type { Page } from 'playwright';

import { checkTemplateStatic } from '../src/check.js';
import { reportDataJsonSchema } from '../src/contract.js';
import { readTemplateDir } from '../src/disk.js';
import { renderTemplate, toDocument, type TemplateBundle } from '../src/engine.js';
import { exampleReportData } from '../src/example.js';
import {
  BUILTIN_TEMPLATE_IDS,
  DEFAULT_TEMPLATE_ID,
  TEMPLATE_ID_PATTERN,
  isBuiltinTemplateId,
  isReservedTemplateId,
  resolveTemplateAlias,
} from '../src/manifest.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(HERE, '..');
const ROOT = path.resolve(PKG, '..', '..');
const BUILTIN_DIR = path.join(PKG, 'builtin');
const USER_DIR = path.join(ROOT, 'templates');
const FONTS_DIR = path.join(ROOT, 'apps', 'web', 'public', 'fonts');

function arg(name: string): string | null {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1) return null;
  const v = process.argv[i + 1];
  return v && !v.startsWith('--') ? v : '';
}

function resolveDir(id: string): string {
  const builtin = resolveTemplateAlias(id);
  if (isBuiltinTemplateId(builtin)) return path.join(BUILTIN_DIR, builtin);
  const user = path.join(USER_DIR, id);
  if (existsSync(user)) return user;
  const asPath = path.resolve(process.env.INIT_CWD ?? process.cwd(), id);
  if (existsSync(path.join(asPath, 'manifest.json'))) return asPath;
  throw new Error(`modèle introuvable : ${id} (ni intégré, ni dans templates/${id})`);
}

async function load(id: string): Promise<{ dir: string; bundle: TemplateBundle }> {
  const dir = resolveDir(id);
  const { bundle, issues } = await readTemplateDir(dir, dir.startsWith(BUILTIN_DIR));
  for (const i of issues)
    console.log(`${i.level === 'error' ? '✗' : '!'} ${i.file ?? ''} ${i.message}`);
  if (!bundle) throw new Error('manifest invalide');
  return { dir, bundle };
}

async function renderDoc(bundle: TemplateBundle, mode: 'web' | 'print'): Promise<string> {
  const data = exampleReportData(bundle, mode);
  const out = await renderTemplate(bundle, data, {
    fonts: { heading: 'inter', body: 'inter', custom: null },
  });
  return toDocument(out, `${bundle.manifest.name} : aperçu`);
}

async function cmdBundle(): Promise<void> {
  const entries: string[] = [];
  for (const id of BUILTIN_TEMPLATE_IDS) {
    const { bundle, issues } = await readTemplateDir(path.join(BUILTIN_DIR, id), true);
    const errors = issues.filter((i) => i.level === 'error');
    if (!bundle || errors.length > 0) {
      throw new Error(`${id}: ${errors.map((e) => `${e.file ?? ''} ${e.message}`).join('; ')}`);
    }
    entries.push(
      `  ${JSON.stringify(id)}: { files: ${JSON.stringify(bundle.files)}, preview: ${bundle.preview ? JSON.stringify(bundle.preview) : 'null'} }`,
    );
  }
  const src = `// Generated by \`pnpm --filter @mynto/templates bundle\` from builtin/<id>/. Do not edit.\nexport const BUILTIN_TEMPLATE_FILES: Record<\n  ${BUILTIN_TEMPLATE_IDS.map((id) => `'${id}'`).join(' | ')},\n  { files: Record<string, string>; preview: string | null }\n> = {\n${entries.join(',\n')},\n};\n`;
  await writeFile(path.join(PKG, 'src', 'builtin.generated.ts'), src);
  const docs = path.join(ROOT, 'docs', 'templates');
  await mkdir(docs, { recursive: true });
  await writeFile(
    path.join(docs, 'report-data.schema.json'),
    `${JSON.stringify(reportDataJsonSchema(), null, 2)}\n`,
  );
  const std = await readTemplateDir(path.join(BUILTIN_DIR, DEFAULT_TEMPLATE_ID), true);
  if (std.bundle) {
    await writeFile(
      path.join(docs, 'example-data.json'),
      `${JSON.stringify(exampleReportData(std.bundle, 'web'), null, 2)}\n`,
    );
  }
  console.log('builtin.generated.ts, report-data.schema.json, example-data.json écrits');
}

async function cmdNew(id: string): Promise<void> {
  if (!TEMPLATE_ID_PATTERN.test(id) || isReservedTemplateId(id)) {
    throw new Error('id : minuscules, chiffres et tirets, 2 à 40 caractères, pas un id intégré');
  }
  const from = resolveTemplateAlias(arg('from') ?? DEFAULT_TEMPLATE_ID);
  const src = resolveDir(from);
  const dest = path.join(USER_DIR, id);
  if (existsSync(dest)) throw new Error(`templates/${id} existe déjà`);
  await mkdir(USER_DIR, { recursive: true });
  await cp(src, dest, { recursive: true });
  const manifestPath = path.join(dest, 'manifest.json');
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8')) as Record<string, unknown>;
  manifest.id = id;
  manifest.name = (arg('name') ?? '') || `${String(manifest.name)} (copie)`;
  manifest.version = '1.0.0';
  manifest.based_on = from;
  delete manifest.author;
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`templates/${id} créé depuis ${from}.`);
  console.log(`Aperçu : pnpm template:preview ${id}   Vérification : pnpm template:check ${id}`);
}

function cmdPreview(id: string): void {
  const port = Number(arg('port') ?? 4310);
  const dir = resolveDir(id);
  const reloadScript = `<script>let v=null;setInterval(async()=>{try{const r=await fetch('/__v');const t=await r.text();if(v!==null&&t!==v)location.reload();v=t;}catch{}},800)</script>`;
  const server = createServer((req, res) => {
    void (async () => {
      const url = new URL(req.url ?? '/', 'http://localhost');
      if (url.pathname === '/__v') {
        const { stat, readdir } = await import('node:fs/promises');
        let m = 0;
        const walk = async (d: string): Promise<void> => {
          for (const e of await readdir(d, { withFileTypes: true })) {
            const p = path.join(d, e.name);
            if (e.isDirectory()) await walk(p);
            else m = Math.max(m, (await stat(p)).mtimeMs);
          }
        };
        await walk(dir);
        res.end(String(m));
        return;
      }
      if (url.pathname.startsWith('/fonts/')) {
        const f = path.join(FONTS_DIR, path.basename(url.pathname));
        if (!existsSync(f)) {
          res.statusCode = 404;
          res.end();
          return;
        }
        res.setHeader('content-type', 'font/woff2');
        res.end(await readFile(f));
        return;
      }
      try {
        const { bundle } = await readTemplateDir(dir);
        if (!bundle) throw new Error('manifest invalide');
        const mode = url.searchParams.get('mode') === 'print' ? 'print' : 'web';
        const html = await renderDoc(bundle, mode);
        res.setHeader('content-type', 'text/html; charset=utf-8');
        res.end(html.replace('</body>', `${reloadScript}</body>`));
      } catch (err) {
        res.setHeader('content-type', 'text/html; charset=utf-8');
        res.end(
          `<pre style="padding:24px;color:#b91c1c">${(err as Error).message.replace(/</g, '&lt;')}</pre>${reloadScript}`,
        );
      }
    })();
  });
  server.listen(port, '127.0.0.1', () => {
    console.log(
      `Aperçu de ${id} : http://127.0.0.1:${String(port)}/  (PDF : ?mode=print). Ctrl+C pour arrêter.`,
    );
  });
}

async function cmdCheck(id: string): Promise<void> {
  const { dir, bundle } = await load(id);
  let failed = false;
  const report = await checkTemplateStatic(bundle);
  for (const i of report.issues) {
    console.log(`${i.level === 'error' ? '✗' : '!'} ${i.file ?? ''} ${i.message}`);
  }
  if (!report.ok) failed = true;
  else console.log('✓ manifest, rendu web et PDF, structure accessible');

  if (!failed) {
    const { chromium } = await import('playwright');
    const axeSource = await readFile(
      path.join(path.dirname(fileURLToPath(import.meta.resolve('axe-core'))), 'axe.min.js'),
      'utf8',
    );
    const fonts = await readFileMap();
    const browser = await chromium.launch({ headless: true });
    try {
      for (const viewport of [
        { name: 'ordinateur', width: 1280, height: 900 },
        { name: 'mobile', width: 390, height: 844 },
      ]) {
        const page = await browser.newPage({ viewport });
        const webDoc = await renderDoc(bundle, 'web');
        await routeFonts(page, fonts, webDoc);
        await page.goto('http://template.local/', { waitUntil: 'load' });
        await page.addScriptTag({ content: axeSource });
        const result = (await page.evaluate(async () => {
          const w = window as unknown as {
            axe: {
              run: (
                ctx: unknown,
                opts: unknown,
              ) => Promise<{
                violations: { id: string; impact: string; help: string; nodes: unknown[] }[];
              }>;
            };
          };
          return w.axe.run(document, {
            runOnly: {
              type: 'tag',
              values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'best-practice'],
            },
          });
        })) as { violations: { id: string; impact: string; help: string; nodes: unknown[] }[] };
        const blocking = result.violations.filter(
          (v) => v.impact === 'serious' || v.impact === 'critical',
        );
        for (const v of result.violations) {
          console.log(
            `${blocking.includes(v) ? '✗' : '!'} axe (${viewport.name}) ${v.id} : ${v.help} (${String(v.nodes.length)})`,
          );
        }
        if (blocking.length > 0) failed = true;
        else console.log(`✓ axe-core ${viewport.name} : aucune violation bloquante`);
        const overflow = await page.evaluate(
          () => document.documentElement.scrollWidth > window.innerWidth + 1,
        );
        if (overflow) {
          console.log(`✗ défilement horizontal en ${viewport.name}`);
          failed = true;
        }
        if (viewport.name === 'ordinateur' && process.argv.includes('--update-preview')) {
          await page.setViewportSize({ width: 1200, height: 900 });
          const png = await page.screenshot({ clip: { x: 0, y: 0, width: 1200, height: 900 } });
          await writeFile(path.join(dir, 'preview.png'), png);
          console.log('✓ preview.png mis à jour');
        }
        await page.close();
      }
      const page = await browser.newPage();
      await routeFonts(page, fonts, await renderDoc(bundle, 'print'));
      await page.emulateMedia({ media: 'print' });
      await page.goto('http://template.local/', { waitUntil: 'load' });
      await page.evaluate(async () => {
        await document.fonts.ready;
      });
      const pdf = await page.pdf({ format: 'A4', printBackground: true, preferCSSPageSize: true });
      const pages = (pdf.toString('latin1').match(/\/Type\s*\/Page[^s]/g) ?? []).length;
      const out = arg('pdf');
      if (out) await writeFile(path.resolve(process.env.INIT_CWD ?? process.cwd(), out), pdf);
      if (pdf.length < 1000 || pages === 0) {
        console.log('✗ impression PDF vide');
        failed = true;
      } else console.log(`✓ impression PDF : ${String(pages)} pages`);
    } finally {
      await browser.close();
    }
  }
  if (failed) {
    console.log(`\n${id} : à corriger.`);
    process.exitCode = 1;
  } else console.log(`\n${id} : prêt.`);
}

async function readFileMap(): Promise<Map<string, Buffer>> {
  const { readdir } = await import('node:fs/promises');
  const map = new Map<string, Buffer>();
  if (!existsSync(FONTS_DIR)) return map;
  for (const f of await readdir(FONTS_DIR)) {
    if (f.endsWith('.woff2')) map.set(f, await readFile(path.join(FONTS_DIR, f)));
  }
  return map;
}

async function routeFonts(page: Page, fonts: Map<string, Buffer>, doc: string): Promise<void> {
  await page.route('**/*', async (route) => {
    const url = new URL(route.request().url());
    if (url.host === 'template.local' && url.pathname === '/') {
      await route.fulfill({ body: doc, contentType: 'text/html; charset=utf-8' });
      return;
    }
    const name = path.basename(url.pathname);
    if (url.pathname.startsWith('/fonts/') && fonts.has(name)) {
      await route.fulfill({ body: fonts.get(name), contentType: 'font/woff2' });
      return;
    }
    // A template never reaches the network.
    if (url.protocol === 'http:' || url.protocol === 'https:') {
      await route.fulfill({ status: 404, body: '' });
      return;
    }
    await route.continue();
  });
}

async function main(): Promise<void> {
  const [cmd, id] = process.argv.slice(2);
  switch (cmd) {
    case 'bundle':
      return cmdBundle();
    case 'new':
      if (!id) throw new Error('usage : template:new <id> --from minimal');
      return cmdNew(id);
    case 'preview':
      if (!id) throw new Error('usage : template:preview <id>');
      cmdPreview(id);
      return;
    case 'check':
      if (!id) throw new Error('usage : template:check <id>');
      return cmdCheck(id);
    default:
      console.log('commandes : new <id> --from <modèle>, preview <id>, check <id>, bundle');
  }
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
