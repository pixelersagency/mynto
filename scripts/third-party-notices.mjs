#!/usr/bin/env node
// Regenerates THIRD_PARTY_NOTICES.md from the installed production
// dependencies (`pnpm licenses list --prod --json`).
//   pnpm licenses:notices
// The "notable licenses" section at the top is hand-written in this file:
// update it when a dependency with a non-permissive license comes in.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const raw = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
  cwd: ROOT,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const byLicense = JSON.parse(raw);

// Platform-specific prebuilt binaries: the list depends on the machine that
// runs the script, the notes below cover every platform.
const PLATFORM = /-(darwin|linux|win32|freebsd)-|-(x64|arm64)$/;

const rows = [];
for (const [license, pkgs] of Object.entries(byLicense)) {
  for (const p of pkgs) {
    if (PLATFORM.test(p.name)) continue;
    rows.push({ name: p.name, versions: p.versions.join(', '), license });
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name));
const counts = new Map();
for (const r of rows) counts.set(r.license, (counts.get(r.license) ?? 0) + 1);

const lines = [
  '# Third-party notices',
  '',
  'mynto is distributed under the GNU Affero General Public License v3.0 only (see `LICENSE`).',
  'It depends on the third-party packages listed below, each under its own license.',
  '',
  'Generated by `pnpm licenses:notices` (`scripts/third-party-notices.mjs`) from the production',
  'dependency tree. Do not edit the package list by hand.',
  '',
  '## Notable licenses and compatibility with AGPL-3.0',
  '',
  '- **MPL-2.0** (`axe-core`, `@axe-core/playwright`): file-level copyleft. Used unmodified, as a',
  '  library; compatible with the AGPL-3.0 (MPL-2.0 section 3.3). Modified MPL files would have',
  '  to stay under the MPL-2.0.',
  '- **Apache-2.0** (Playwright, Lighthouse, the Anthropic SDK, TypeScript tooling...): compatible',
  '  with GPLv3 / AGPLv3. Their NOTICE files ship inside their packages.',
  '- **Chromium** (downloaded by Playwright, preinstalled in the scanner image): BSD-3-Clause and',
  '  other permissive licenses, see `chrome://credits` in the binary.',
  '- **LGPL-3.0-or-later** (`@img/sharp-libvips-*`, prebuilt libvips used by `sharp`, an optional',
  '  dependency of Next.js image optimization): dynamically linked, unmodified; compatible.',
  '- **OFL-1.1** (report and dashboard fonts, Newsreader included, copied from `@fontsource/*` into `apps/web/public/fonts`, see',
  '  `apps/web/public/fonts/LICENSES.txt`): fonts may be bundled and redistributed with software,',
  '  not sold on their own.',
  '- **CC-BY-4.0** (`caniuse-lite`, data only) and **Python-2.0** (`argparse`): permissive.',
  '- **Unlicense / 0BSD / MIT-0 / ISC / BSD / MIT**: permissive.',
  '',
  'No dependency is under a license incompatible with the AGPL-3.0 (no SSPL, BUSL, Commons Clause',
  'or proprietary terms).',
  '',
  '## Summary',
  '',
  '| License | Packages |',
  '|---|---|',
  ...[...counts.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${String(n)} |`),
  '',
  '## Packages',
  '',
  '| Package | Version | License |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.versions} | ${r.license} |`),
  '',
];
writeFileSync(path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
process.stderr.write(`THIRD_PARTY_NOTICES.md: ${String(rows.length)} packages\n`);
